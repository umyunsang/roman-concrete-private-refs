def _block_poly(te):
    """벽면 글 블록 평행사변형(윗변 식 + 세로 두께). ↗: y = d − tan30·x, ↘: y = c + tan30·x"""
    x0, x1 = te["x"]
    t = te.get("thickness", te.get("thickness_max"))
    if "d" in te:
        f = lambda x: te["d"] - _K * x  # noqa: E731
    else:
        f = lambda x: te["c"] + _K * x  # noqa: E731
    return [[x0, round(f(x0), 2)], [x1, round(f(x1), 2)], [x1, round(f(x1) + t, 2)], [x0, round(f(x0) + t, 2)]]


