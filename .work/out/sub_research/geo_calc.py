COMPASS16 = [
    "북", "북북동", "북동", "동북동", "동", "동남동", "남동", "남남동",
    "남", "남남서", "남서", "서남서", "서", "서북서", "북서", "북북서",
]


def haversine(lat1, lon1, lat2, lon2):
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = p2 - p1
    dl = math.radians(lon2 - lon1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * R * math.asin(math.sqrt(a))


def bearing(lat1, lon1, lat2, lon2):
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dl = math.radians(lon2 - lon1)
    x = math.sin(dl) * math.cos(p2)
    y = math.cos(p1) * math.sin(p2) - math.sin(p1) * math.cos(p2) * math.cos(dl)
    return (math.degrees(math.atan2(x, y)) + 360.0) % 360.0


def compass(deg):
    return COMPASS16[int((deg + 11.25) // 22.5) % 16]


def table(origin_name, only_groups=None):
    lat0, lon0 = ORIGINS[origin_name]
    rows = []
    for name, lat, lon, group in POINTS:
        if only_groups and group not in only_groups:
            continue
        d = haversine(lat0, lon0, lat, lon)
        if d < 0.05:
            continue
        b = bearing(lat0, lon0, lat, lon)
        rows.append((name, lat, lon, group, d, b))
    rows.sort(key=lambda r: r[4])
    out = [f"### 기준점: {origin_name} ({lat0:.4f}, {lon0:.4f})", "",
           "| 대상 | 위도 | 경도 | 묶음 | 거리(km) | 방위(°) | 16방위 |",
           "|---|---|---|---|---|---|---|"]
    for name, lat, lon, group, d, b in rows:
        dist = f"{d:.1f}" if d < 100 else f"{d:.0f}"
        out.append(f"| {name} | {lat:.4f} | {lon:.4f} | {group} | {dist} | {b:.0f} | {compass(b)} |")
    return "\n".join(out)


