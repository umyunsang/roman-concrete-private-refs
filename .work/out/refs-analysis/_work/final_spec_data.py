def iso(ox, oy, X, Y):
    return (ox + C30 * (X - Y), oy + 0.5 * (X + Y))


def walk(start, steps):
    """steps: [(방향, 길이)] 방향 SE ↘ / SW ↙ / NE ↗ / NW ↖"""
    d = {"SE": (C30, 0.5), "SW": (-C30, 0.5), "NE": (C30, -0.5), "NW": (-C30, -0.5)}
    pts = [tuple(start)]
    for k, l in steps:
        x, y = pts[-1]
        pts.append((round(x + d[k][0] * l, 2), round(y + d[k][1] * l, 2)))
    return pts


