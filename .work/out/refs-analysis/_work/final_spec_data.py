def cell_center(k):                # k = 1..7
    x = X_L if k % 2 == 1 else X_R
    return (x, Y1 + (k - 1) * CELL_HH)


def cell_verts(k):
    cx, cy = cell_center(k)
    hw = CELL_W / 2.0
    return {"T": (cx, cy - CELL_HH), "R": (cx + hw, cy), "B": (cx, cy + CELL_HH), "L": (cx - hw, cy)}


def board_poly(k, edge, h, frac=(0.0, 1.0)):
    """셀 k의 뒤 변 위에 세운 수직 보드. edge: 'UL'(뒤-왼쪽 변, −X면, 글줄 ↗) 또는 'UR'(뒤-오른쪽 변, −Y면, 글줄 ↘)."""
    v = cell_verts(k)
    a, b = (v["L"], v["T"]) if edge == "UL" else (v["T"], v["R"])
    f0, f1 = frac
    p0 = (a[0] + (b[0] - a[0]) * f0, a[1] + (b[1] - a[1]) * f0)
    p1 = (a[0] + (b[0] - a[0]) * f1, a[1] + (b[1] - a[1]) * f1)
    return [p0, p1, (p1[0], p1[1] - h), (p0[0], p0[1] - h)]


