def arena_oct():
    ox, oy = ARENA_C
    return [iso(ox, oy, ARENA_R * math.cos(math.radians(22.5 + 45 * k)), ARENA_R * math.sin(math.radians(22.5 + 45 * k))) for k in range(8)]


def arena_ring_pt(theta_deg, z=0.0):
    ox, oy = ARENA_C
    X = ARENA_RING * math.cos(math.radians(theta_deg))
    Y = ARENA_RING * math.sin(math.radians(theta_deg))
    x, y = iso(ox, oy, X, Y)
    return (x, y - z)


def arena_box():
    o = arena_oct()
    xs = [p[0] for p in o]
    ys = [p[1] for p in o]
    top = min(arena_ring_pt(t, ARENA_FRAG_H)[1] for t in range(270, 361, 5))   # 오른쪽 1/4 조각
    top = min(top, min(arena_ring_pt(t, ARENA_BACK_H)[1] for t in range(225, 271, 5)))
    return [min(xs), top, max(xs), max(ys) + ARENA_T]


